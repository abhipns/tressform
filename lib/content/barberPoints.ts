/** A point split into its label ("Sides") and what follows ("low taper…"). */
export function splitPoint(point: string): { label: string | null; text: string } {
  const i = point.indexOf(": ");
  if (i > 0 && i <= 20) return { label: point.slice(0, i), text: point.slice(i + 2) };
  return { label: null, text: point };
}
